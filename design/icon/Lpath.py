"""圆角 L 的 SVG path 生成器。

坐标系 = 自适应图标的 108dp 画布，原点左上。
路径顺时针：左上角 → 竖笔右沿 → 右上角 → 竖到内角 → 横笔上沿 →
右端上角 → 右端下角 → 底边 → 左下角 → 左上角。

关键点：每一段直线都要先减掉两端圆弧占掉的 r，否则形状会整体变形
（圆弧画完自己会补上剩下的那截）。
"""

def letter_l(x0, y0, x1, y1, sw, r):
    """(x0,y0)=左上角，(x1,y1)=右下角，sw=笔画宽，r=外角半径。"""
    xm = x0 + sw      # 竖笔右沿，也是内角的 x
    ym = y1 - sw      # 横笔上沿，也是内角的 y
    return (
        f"M{x0+r},{y0} "
        f"h{xm-x0-2*r} "
        f"a{r},{r} 0 0 1 {r},{r} "
        f"v{ym-y0-r} "
        f"h{x1-xm-r} "
        f"a{r},{r} 0 0 1 {r},{r} "
        f"v{sw-2*r} "
        f"a{r},{r} 0 0 1 -{r},{r} "
        f"h-{x1-x0-2*r} "
        f"a{r},{r} 0 0 1 -{r},-{r} "
        f"v-{y1-y0-2*r} "
        f"a{r},{r} 0 0 1 {r},-{r} "
        "z"
    )

if __name__ == "__main__":
    print(letter_l(33, 27, 75, 81, 21, 9))
